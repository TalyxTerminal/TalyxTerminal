export function indicatorLabel(source: string, label: string): string {
  return source === "builtin" ? labels[label] ?? label : label;
}

export function displayIndicator(entry: CatalogEntry): CatalogEntry {
  if (entry.source !== "builtin") return entry;
  return { ...entry, ...builtins[entry.id], shortTitle: indicatorLabel(entry.source, entry.shortTitle),
    category: indicatorLabel(entry.source, entry.category),
    inputs: entry.inputs.map(input => ({ ...input, title: indicatorLabel(entry.source, input.title),
      tooltip: input.tooltip && indicatorLabel(entry.source, input.tooltip) })) };
}
