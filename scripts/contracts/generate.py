"""Generate each declared module's contract and clients from its code; ``--check`` fails on anything stale.

For every module with a version-5 manifest (and the platform), this imports its backend entry, builds
``public/contract.json`` from the decorators and types, and writes from that contract:

- ``public/ts/types.tsx``: TypeScript types and ``createClient(ctx)`` for frontends (the platform's goes into the SDK,
  ``sdk/ui/src/platform.tsx``, exported as ``Platform`` from @talyx/sdk);
- ``public/python/client.py``: a Python client for other modules' backends (JSON in, JSON out).

Nobody edits these files: change the declarations and run this again.
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT), str(ROOT / "sdk")]

from talyx_sdk.contract import build  # noqa: E402

BANNER = "Generated by scripts/contracts/generate.py from the module's declarations. Do not edit."


def declared_modules(only: set[str] | None = None) -> list[tuple[str, Path, str]]:
    """``(id, module directory, import name of the entry)`` of every version-5 module, the platform first."""
    found = [("platform", ROOT / "host", "host.platform.declarations")]
    for manifest in sorted((ROOT / "modules").glob("*/talyx.module.json")):
        value = json.loads(manifest.read_text(encoding="utf-8"))
        if value.get("manifestVersion") != 5:
            continue
        found.append((value["id"], manifest.parent, f"modules.{manifest.parent.name}.{value['entries']['backend']}"))
    return [item for item in found if only is None or item[0] in only]


def _camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[._]", name))


def _untitled(node, names: bool = False):
    """pydantic titles every schema; TypeScript should name only the declared types (``$defs``). ``names``: the node
    maps names to schemas (``properties``, ``$defs``), so a property called ``title`` stays."""
    if isinstance(node, dict):
        return {key: _untitled(value, not names and key in ("properties", "$defs", "patternProperties"))
                for key, value in node.items() if names or key != "title"}
    if isinstance(node, list):
        return [_untitled(item) for item in node]
    return node


def typescript(contract: dict, owner: str, work: Path, manifest: dict) -> str:
    properties = {}
    for name, spec in manifest.get("views", {}).items():
        properties["view:" + name] = spec.get("props", {"type": "object"})  # the manifest may leave a view's props out
        for event, payload in spec.get("emits", {}).items():
            properties[f"view:{name}:{event}"] = payload
    for name, spec in contract["actions"].items():
        properties[name] = {"type": "object", "title": _camel(name) + "Operation",
                            "properties": {"input": spec["input"], "output": spec["output"]},
                            "required": ["input", "output"], "additionalProperties": False}
    for name, spec in contract["streams"].items():
        properties["stream:" + name] = {"type": "object", "title": _camel(name) + "Stream",
                                        "properties": {"params": spec["params"], "item": spec["item"]},
                                        "required": ["params", "item"], "additionalProperties": False}
    for name, spec in contract["events"].items():
        properties["event:" + name] = spec["payload"]
    for name, spec in contract["extensionPoints"].items():
        properties["point:" + name] = spec["descriptor"]
    definitions = {name: {**_untitled(value), **({"title": value["title"]} if "title" in value else {})}
                   for name, value in contract["$defs"].items()}
    schema = {"title": "ContractTypes", "type": "object", "properties": _untitled(properties, True),
              "required": list(properties), "additionalProperties": False, "$defs": definitions}
    source, output = work / f"{owner}.json", work / f"{owner}.ts"
    source.write_text(json.dumps(schema), encoding="utf-8")
    subprocess.run(["node", str(ROOT / "web/scripts/contract-types.mjs"), str(source), str(output)], check=True,
                   shell=sys.platform == "win32")
    types = output.read_text(encoding="utf-8")
    tasks = [name for name, spec in contract["actions"].items() if spec["task"]]
    actions = [name for name in contract["actions"]]
    sdk = "./linkage" if owner == "platform" else "@talyx/sdk"
    return (f"/* {BANNER} */\n/* eslint-disable */\nimport {{ client, type TypedClient }} from \"{sdk}\";\n\n"
            + types
            + f"\nexport const MODULE = {json.dumps(owner)};\n"
            + f"export const ACTIONS = {json.dumps(actions)} as const;\n"
            + "/** Actions that answer with a task id at once; read the result with platform.tasks. */\n"
            + f"export const TASKS = {json.dumps(tasks)} as const;\n"
            + "export type Actions = { [K in (typeof ACTIONS)[number]]: ContractTypes[K] };\n"
            + "export function createClient(ctx: Parameters<typeof client>[0]): TypedClient<Actions, "
              "(typeof TASKS)[number]> {\n"
            + f"  return client<Actions, (typeof TASKS)[number]>(ctx, {json.dumps(owner)});\n}}\n")


def python_client(contract: dict, owner: str) -> str:
    lines = [f'"""{BANNER}', "", f"Calls {owner}'s public actions from another module's backend. Inputs and results are",
             'JSON values as described in contract.json."""', "", "from __future__ import annotations", "",
             *(["from typing import Any", ""] if contract["actions"] else []), "", f"class {_camel(owner)}Client:",
             f'    """{owner}\'s actions; ``workspace`` is the workspace the call is made for."""', "",
             "    def __init__(self, ctx):", "        self.ctx = ctx", ""]
    for name, spec in contract["actions"].items():
        method = name.replace(".", "_")
        summary = spec["description"].split("\n")[0][:200].replace('"""', "'")
        returns = "a task id" if spec["task"] else "the result"
        lines += [f"    async def {method}(self, input: dict, *, workspace: str | None = None) -> Any:",
                  f'        """{summary} Returns {returns}."""',
                  f"        return await self.ctx.call({json.dumps(owner + '.' + name)}, input, workspace=workspace)", ""]
    for name in contract["streams"]:
        lines += [f"    async def subscribe_{name.replace('.', '_')}(self, params: dict, *, workspace: str | None = None, cursor=None):",
                  f"        return await self.ctx.subscribe({json.dumps(owner + '.' + name)}, params, "
                  "workspace=workspace, cursor=cursor)", ""]
    return "\n".join(lines).rstrip() + "\n"


def module_at(directory: Path) -> tuple[str, Path, str]:
    """A module outside ``modules/`` (an installed one): its package is imported from its parent folder."""
    value = json.loads((directory / "talyx.module.json").read_text(encoding="utf-8"))
    if directory.parent.resolve() == (ROOT / "modules").resolve():
        return value["id"], directory, f"modules.{directory.name}.{value['entries']['backend']}"
    sys.path.insert(0, str(directory.parent))
    return value["id"], directory, f"{directory.name}.{value['entries']['backend']}"


def outputs(only: set[str] | None = None, directories: list[Path] = ()) -> dict[Path, str]:
    result = {}
    selected = [module_at(path) for path in directories] if directories else declared_modules(only)
    with tempfile.TemporaryDirectory() as folder:
        for owner, directory, entry in selected:
            module = importlib.import_module(entry).module
            contract = build(module)
            public = directory / "public"
            result[public / "contract.json"] = json.dumps(contract, indent=1, ensure_ascii=False) + "\n"
            manifest = json.loads((directory / "talyx.module.json").read_text(encoding="utf-8")) \
                if owner != "platform" else {}
            # The platform's frontend client is part of the SDK: modules reach it as ``Platform`` from @talyx/sdk.
            types = ROOT / "sdk/ui/src/platform.tsx" if owner == "platform" else public / "ts" / "types.tsx"
            result[types] = typescript(contract, owner, Path(folder), manifest)
            result[public / "python" / "client.py"] = python_client(contract, owner)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs")
    parser.add_argument("--module-dir", action="append", type=Path, default=[], help="a module's folder")
    parser.add_argument("modules", nargs="*", help="only these modules")
    args = parser.parse_args()
    stale = []
    for path, content in outputs(set(args.modules) or None, args.module_dir).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print("wrote", path)
    if stale:
        print("Generated files differ from the declarations (run scripts/contracts/generate.py):\n  "
              + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
