import { compile } from "json-schema-to-typescript";
import { readFile, writeFile } from "node:fs/promises";
const [input, output] = process.argv.slice(2);
const schema = JSON.parse(await readFile(input, "utf8"));

// The compiler uses the pre-2020 tuple form. Adapt schema nodes only, leaving
// instance data (for example defaults and enum values) unchanged.
function compilerSchema(node) {
  if (node === null || typeof node !== "object" || Array.isArray(node)) return node;
  const adapted = { ...node };
  for (const key of ["properties", "patternProperties", "definitions", "$defs", "dependentSchemas", "dependencies"]) {
    if (node[key] && typeof node[key] === "object" && !Array.isArray(node[key])) {
      adapted[key] = Object.fromEntries(Object.entries(node[key]).map(([name, value]) => [name, compilerSchema(value)]));
    }
  }
  for (const key of ["items", "additionalItems", "prefixItems", "contains", "additionalProperties", "unevaluatedItems", "unevaluatedProperties", "propertyNames", "allOf", "anyOf", "oneOf", "not", "if", "then", "else", "contentSchema"]) {
    if (key in node) adapted[key] = Array.isArray(node[key]) ? node[key].map(compilerSchema) : compilerSchema(node[key]);
  }
  if (Array.isArray(node.prefixItems)) {
    adapted.additionalItems = "items" in node ? adapted.items : true;
    adapted.items = adapted.prefixItems;
    delete adapted.prefixItems;
  }
  return adapted;
}

const content = await compile(compilerSchema(schema), "Vocabulary", { bannerComment: "/* Generated by json-schema-to-typescript. Edit the declaration. */", declareExternallyReferenced: true, unreachableDefinitions: true });
await writeFile(output, content);
